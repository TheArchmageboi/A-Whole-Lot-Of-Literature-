local function addItemToList(listName, itemName, weight)
    local list = ProceduralDistributions.list[listName]
    if list and list.items then
        table.insert(list.items, itemName)
        table.insert(list.items, weight)
    end
end

local minYear = 1920
if SandboxVars and SandboxVars.WholeLotOfLiterature and SandboxVars.WholeLotOfLiterature.MinYear then
    minYear = SandboxVars.WholeLotOfLiterature.MinYear
end

local maxYear = 2000
if SandboxVars and SandboxVars.WholeLotOfLiterature and SandboxVars.WholeLotOfLiterature.MaxYear then
    maxYear = SandboxVars.WholeLotOfLiterature.MaxYear
end

if minYear > maxYear then
    minYear, maxYear = maxYear, minYear
end

local spawnRate = 2
if SandboxVars and SandboxVars.WholeLotOfLiterature and SandboxVars.WholeLotOfLiterature.SpawnRate then
    spawnRate = SandboxVars.WholeLotOfLiterature.SpawnRate
end

local spawnMultiplier = 1.0
if spawnRate == 1 then
    spawnMultiplier = 0.5
elseif spawnRate == 3 then
    spawnMultiplier = 1.5
elseif spawnRate == 4 then
    spawnMultiplier = 2.5
end

local enableMod = true
if SandboxVars and SandboxVars.WholeLotOfLiterature and SandboxVars.WholeLotOfLiterature.EnableMod ~= nil then
    enableMod = SandboxVars.WholeLotOfLiterature.EnableMod
end

if enableMod then
    for _, book in ipairs(books) do
        if book.year >= minYear and book.year <= maxYear then
            for listName, baseWeight in pairs(locationWeights) do
                addItemToList(listName, book.itemName, baseWeight * spawnMultiplier)
            end
            local bonusList = ProceduralDistributions.list[book.bookstore]
            if bonusList then
                addItemToList(book.bookstore, book.itemName, 1.2 * spawnMultiplier)
            end
        end
    end
end
